#!/bin/bash
# Demo PKI for the Versal firmware update demo: ECDSA P-384 CA, server and device
# certificates, plus a second "rogue" CA and device certificate for the
# refused-client scenario. Not for production.
# usage: gen_certs.sh            (writes certs/ and certs_rogue/ next to it)
set -eo pipefail
cd "$(dirname "$0")"
SERVER_IP=${SERVER_IP:-192.168.2.1}

mk() { # dir ca-cn device-cn
    d=$1
    mkdir -p $d
    openssl ecparam -name secp384r1 -genkey -noout -out $d/ca-key.pem
    openssl req -x509 -new -key $d/ca-key.pem -sha384 -days 3650 \
        -subj "/O=wolfSSL Demo/CN=$2" -out $d/ca-cert.pem
    openssl ecparam -name secp384r1 -genkey -noout -out $d/server-key.pem
    openssl req -new -key $d/server-key.pem \
        -subj "/O=wolfSSL Demo/CN=ota-server.local" -out $d/server.csr
    printf 'basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:ota-server.local,IP:%s\n' "$SERVER_IP" > $d/server.ext
    openssl x509 -req -in $d/server.csr -CA $d/ca-cert.pem -CAkey $d/ca-key.pem \
        -CAcreateserial -sha384 -days 3650 -extfile $d/server.ext \
        -out $d/server-cert.pem 2>/dev/null
    openssl ecparam -name secp384r1 -genkey -noout -out $d/device-key.pem
    openssl req -new -key $d/device-key.pem \
        -subj "/O=wolfSSL Demo/CN=$3" -out $d/device.csr
    printf 'basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\n' > $d/device.ext
    openssl x509 -req -in $d/device.csr -CA $d/ca-cert.pem -CAkey $d/ca-key.pem \
        -CAcreateserial -sha384 -days 3650 -extfile $d/device.ext \
        -out $d/device-cert.pem 2>/dev/null
    openssl x509 -in $d/ca-cert.pem -outform DER -out $d/ca-cert.der
    openssl x509 -in $d/device-cert.pem -outform DER -out $d/device-cert.der
    openssl ec -in $d/device-key.pem -outform DER -out $d/device-key.der 2>/dev/null
    rm -f $d/*.csr $d/*.ext $d/*.srl
}
hdr() { # dir ca-dir   (device cert/key from dir, trusted CA from ca-dir)
    {
        echo "/* Generated by gen_certs.sh - demo PKI, not for production. */"
        echo "#ifndef OTA_DEMO_CERTS_H"
        echo "#define OTA_DEMO_CERTS_H"
        for f in $2/ca-cert $1/device-cert $1/device-key; do
            n=$(basename $f | tr '-' '_')_der
            echo "static const unsigned char ${n}[] = {"
            xxd -i < "$f.der" | sed 's/^/    /'
            echo "};"
        done
        echo "#endif"
    } > $1/ota_certs.h
}
mk certs "Versal Update Demo CA" "versal-device"
mk certs_rogue "Rogue CA" "rogue-device"
hdr certs certs
# The rogue device still trusts the real server CA; only its own identity
# is signed by a CA the server does not know.
hdr certs_rogue certs
echo "Wrote certs/ and certs_rogue/"
